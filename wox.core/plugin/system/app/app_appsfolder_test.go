// TestReconcileExtraAppsPreservesIndexOnEnumerationFailure covers partial snapshots.
func TestReconcileExtraAppsPreservesIndexOnEnumerationFailure(t *testing.T) {
	existing := appInfo{Name: "Installed", Path: extraAppPath("installed!App"), Type: AppTypeUWP}
	app := &ApplicationPlugin{api: newRecordingAppAPI(), retriever: &failingExtraAppsRetriever{}, apps: []appInfo{existing}}
	if app.reconcileExtraApps(context.Background()) || len(app.apps) != 1 || !app.apps[0].equals(existing) {
		t.Fatal("failed enumeration changed the existing index")
	}
}

// TestIndexExtraAppsClassifiesFinalIcons covers both fallback and resolved icons.
func TestIndexExtraAppsClassifiesFinalIcons(t *testing.T) {
	app := &ApplicationPlugin{api: newRecordingAppAPI(), retriever: &preparingExtraAppsRetriever{}}
	apps := app.indexExtraApps(context.Background(), []appInfo{
		{Name: "Fallback", Path: extraAppPath("fallback!App"), Icon: appIcon},
		{Name: "Resolved", Path: extraAppPath("resolved!App"), Icon: common.NewWoxImageAbsolutePath(`C:\cache\resolved.png`), IsDefaultIcon: true},
	}, nil)
	if !apps[0].IsDefaultIcon || app.shouldShowInLaunchpad(apps[0]) {
		t.Fatal("default icon should be excluded from Launchpad")
	}
	if apps[1].IsDefaultIcon || !app.shouldShowInLaunchpad(apps[1]) {
		t.Fatal("resolved icon should be eligible for Launchpad")
	}
}

func TestMergeExtraAppsAddsAndRemovesAppsFolderEntries(t *testing.T) {
	desktop := appInfo{Name: "Cursor", Path: `C:\Apps\Cursor.exe`, Type: AppTypeDesktop}
	oldExtra := appInfo{Name: "Old PWA", Path: extraAppPath("old.example!App"), Type: AppTypeAppsFolder}
	newExtra := appInfo{Name: "YouTube Music", Path: extraAppPath(`music.youtube.com-5929F88E_vezhnr0wkvrcy!App`), Type: AppTypeAppsFolder}

	kept, added, removed, changed := mergeExtraApps(
		[]appInfo{desktop, oldExtra},
		[]appInfo{newExtra},
		strings.ToLower,
	)
	if !changed {
		t.Fatal("expected extra app set to change")
	}
	if len(kept) != 1 || kept[0].Path != desktop.Path {
		t.Fatalf("desktop app should stay, got %#v", kept)
	}
	if len(added) != 1 || added[0].Path != newExtra.Path {
		t.Fatalf("expected YouTube Music to be added, got %#v", added)
	}
	if len(removed) != 1 || removed[0] != oldExtra.Name {
		t.Fatalf("expected old PWA to be removed, got %#v", removed)
	}
}

