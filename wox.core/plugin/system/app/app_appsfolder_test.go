func TestExtraAppsFromFolderEntriesReusesCachedIconsAndAddsNewPWAs(t *testing.T) {
	existingPath := extraAppPath(`Microsoft.WindowsCalculator_8wekyb3d8bbwe!App`)
	existing := appInfo{
		Name: "Calculator",
		Path: existingPath,
		Icon: common.WoxImage{ImageType: common.WoxImageTypeAbsolutePath, ImageData: `C:\cache\calc.png`},
		Type: AppTypeUWP,
	}
	entries := []appsFolderEntry{
		{Name: "计算器", AppID: `Microsoft.WindowsCalculator_8wekyb3d8bbwe!App`, Packaged: true},
		{Name: "YouTube Music", AppID: `music.youtube.com-5929F88E_vezhnr0wkvrcy!App`},
		{Name: "Chrome", AppID: "Chrome"},
	}

	got := extraAppsFromFolderEntries(entries, map[string]appInfo{strings.ToLower(existingPath): existing}, strings.ToLower)
	if len(got) != 2 {
		t.Fatalf("got %d extras, want 2", len(got))
	}
	if got[0].Name != "计算器" || got[0].Icon.ImageData != existing.Icon.ImageData {
		t.Fatalf("expected reused calculator with updated name, got %#v", got[0])
	}
	if got[1].Name != "YouTube Music" || got[1].Type != AppTypeAppsFolder {
		t.Fatalf("expected new PWA entry, got %#v", got[1])
	}
	if got[1].Icon.ImageData != appIcon.ImageData {
		t.Fatalf("discovery should leave new app icons for indexing, got %#v", got[1].Icon)
	}
	if !got[1].IsDefaultIcon {
		t.Fatal("new AppsFolder candidate must be marked as using the default icon")
	}
}

